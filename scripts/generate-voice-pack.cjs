const fs = require('node:fs/promises');
const path = require('node:path');
const ts = require('typescript');
const { synthesize } = require('./navi-tts.cjs');

const languages = ['de', 'en'];
const voice = process.env.NAVI_VOICE || 'marin';

async function loadLearningContent() {
  const sourcePath = path.join(process.cwd(), 'src/data/learningContent.ts');
  const source = await fs.readFile(sourcePath, 'utf8');
  const compiled = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const module = { exports: {} };
  Function('module', 'exports', 'require', compiled)(module, module.exports, require);
  return module.exports.categories;
}

const safeName = (key) => key.replace(/[^a-zA-Z0-9.-]/g, '-');

async function main() {
  const categories = await loadLearningContent();
  const entries = [];

  for (const language of languages) {
    entries.push({ language, key: 'common.wrong', text: language === 'de' ? 'Fast! Versuch es noch einmal.' : 'Almost! Try again.' });
    for (const category of categories) {
      for (const question of category.questions) {
        for (const part of ['prompt', 'success', 'hint']) {
          entries.push({
            language,
            key: `question.${question.id}.${part}`,
            text: question[part][language],
          });
        }
      }
    }
  }

  for (let index = 0; index < entries.length; index += 1) {
    const entry = entries[index];
    const relativePath = path.posix.join('assets/audio', entry.language, `${safeName(entry.key)}.aac`);
    const outputPath = path.join(process.cwd(), relativePath);
    try {
      await fs.access(outputPath);
      process.stdout.write(`[${index + 1}/${entries.length}] exists ${entry.key}\n`);
    } catch {
      process.stdout.write(`[${index + 1}/${entries.length}] generating ${entry.language} ${entry.key}\n`);
      await synthesize({
        apiKey: process.env.OPENAI_API_KEY,
        text: entry.text,
        language: entry.language,
        voice,
        outputPath,
      });
    }
    entry.relativePath = relativePath;
  }

  const lines = [
    "import { Language } from '../types';",
    '',
    '// Generated by scripts/generate-voice-pack.cjs. Do not edit manually.',
    'export const naviVoiceAssets: Record<Language, Record<string, number>> = {',
  ];
  for (const language of languages) {
    lines.push(`  ${language}: {`);
    for (const entry of entries.filter((item) => item.language === language)) {
      const requirePath = `../../${entry.relativePath}`;
      lines.push(`    ${JSON.stringify(entry.key)}: require(${JSON.stringify(requirePath)}),`);
    }
    lines.push('  },');
  }
  lines.push('};', '');
  await fs.mkdir(path.join(process.cwd(), 'src/generated'), { recursive: true });
  await fs.writeFile(path.join(process.cwd(), 'src/generated/naviVoiceManifest.ts'), lines.join('\n'));
  process.stdout.write(`Generated ${entries.length} Navi clips with voice ${voice}.\n`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
